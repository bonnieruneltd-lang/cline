"""
shop/catalog_data.py
====================
Static seed data for the Royal Shop catalog, derived from the agreed spec
("Final Boss Prompt"). Each entry maps to one catalog row.

Key conventions
---------------
* Vanilla items use ``minecraft:<id>``.
* Backported (Modern Content Backport) items use ``backport:<id>``.
* Enchanted books use ``enchant:<enchant_id>:<level>``.
* Multi-piece bundles (armor sets) use ``bundle:<name>`` and are expanded by
  ``BUNDLES`` at order time.
"""


def _item(key, name, category, price, unit_qty=64, *, stackable=True, max_stack=64,
          backported=False, enchant_id=None, enchant_level=None, sort=0):
    return {
        "key": key,
        "display_name": name,
        "category": category,
        "price": price,
        "unit_qty": unit_qty,
        "stackable": 1 if stackable else 0,
        "max_stack": max_stack,
        "is_backported": 1 if backported else 0,
        "enchant_id": enchant_id,
        "enchant_level": enchant_level,
        "sort_order": sort,
    }


